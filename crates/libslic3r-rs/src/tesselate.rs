/// GLU primitive types emitted by the tessellator and consumed by the
/// `tessVertex` callback. Mirrors the OpenGL `GLenum` values used in
/// `tessBegin`/`tessVertex` (Tesselate.cpp:112, 134, 146, 149, 152).
#[derive(Clone, Copy, PartialEq, Eq)]
enum GlPrimitive {
    Triangles,
    TriangleFan,
    TriangleStrip,
}

/// 1:1 port of `class GluTessWrapper` (Tesselate.cpp:9-190).
///
/// The native GLU tessellator is replaced by `earcutr`; the callback state
/// machine (`tess_begin` / `tess_end` / `tess_vertex`) is preserved exactly so
/// that the conversion from the primitive stream to output triangles matches
/// C++.
struct GluTessWrapper {
    // Currently processed primitive type. Tesselate.cpp:176
    m_primitive_type: GlPrimitive,
    // Two last vertices received for m_primitive_type. Used for processing triangle strips, fans etc.
    // Tesselate.cpp:178-179
    m_pt0: [f64; 3],
    m_pt1: [f64; 3],
    // Number of points processed over m_primitive_type. Tesselate.cpp:181
    m_num_points: i32,
    // Triangles generated by the tesselator. Tesselate.cpp:183
    m_output_triangles: Vec<Vec3d>,
    // Intersection points generated by tessCombine callback. There should be none if the input contour is not self intersecting.
    // Tesselate.cpp:185
    m_intersection_points: std::collections::VecDeque<Vec3d>,
    // Fixed third coordinate. Tesselate.cpp:187
    m_z: f64,
    // Output triangles shall be flipped (normal points down). Tesselate.cpp:189
    m_flipped: bool,
}

impl GluTessWrapper {
    /// Tesselate.cpp:11-18 (constructor; GLU tessellator + callback registration)
    fn new() -> Self {
        GluTessWrapper {
            m_primitive_type: GlPrimitive::Triangles,
            m_pt0: [0.0; 3],
            m_pt1: [0.0; 3],
            m_num_points: 0,
            m_output_triangles: Vec::new(),
            m_intersection_points: std::collections::VecDeque::new(),
            m_z: 0.0,
            m_flipped: false,
        }
    }

    /// Tesselate.cpp:23-57 (tesselate3d for a single ExPolygon)
    fn tesselate3d_expoly(&mut self, expoly: &ExPolygon, z_: f64, flipped_: bool) -> Vec<Vec3d> {
        self.m_z = z_; // Tesselate.cpp:25
        self.m_flipped = flipped_; // Tesselate.cpp:26
        self.m_output_triangles.clear(); // Tesselate.cpp:27
        // std::vector<GLdouble> coords; (Tesselate.cpp:28) — earcut consumes a
        // flat coordinate buffer directly; the buffer reservation
        // (Tesselate.cpp:29-34) is irrelevant for the earcut backend.

        // gluTessBeginPolygon / gluTessBeginContour for contour (Tesselate.cpp:35-36),
        // contour vertices (Tesselate.cpp:37-42), gluTessEndContour (Tesselate.cpp:43),
        // each hole as its own contour (Tesselate.cpp:44-53),
        // gluTessEndPolygon (Tesselate.cpp:54) — all of this is the GLU input
        // feeding; here it is replaced by an earcut call over the same contour
        // + holes, the resulting triangles are pushed through tess_vertex.
        self.tesselate_one_expoly(expoly);

        self.m_intersection_points.clear(); // Tesselate.cpp:55
        std::mem::take(&mut self.m_output_triangles) // return std::move(m_output_triangles); (Tesselate.cpp:56)
    }

    /// Tesselate.cpp:59-100 (tesselate3d for a vector of ExPolygons)
    fn tesselate3d_expolys(
        &mut self,
        expolygons: &ExPolygons,
        z_: f64,
        flipped_: bool,
    ) -> Vec<Vec3d> {
        self.m_z = z_; // Tesselate.cpp:61
        self.m_flipped = flipped_; // Tesselate.cpp:62
        self.m_output_triangles.clear(); // Tesselate.cpp:63
        // coords buffer sizing (Tesselate.cpp:64-74) is GLU-specific; not needed.

        // for (const ExPolygon &expoly : expolygons) (Tesselate.cpp:75-97):
        // each ExPolygon is tessellated as its own polygon (gluTessBeginPolygon
        // .. gluTessEndPolygon per expoly). Mirror that by triangulating each
        // ExPolygon independently and appending into m_output_triangles.
        for expoly in expolygons {
            self.tesselate_one_expoly(expoly);
        }

        self.m_intersection_points.clear(); // Tesselate.cpp:98
        std::mem::take(&mut self.m_output_triangles) // return std::move(m_output_triangles); (Tesselate.cpp:99)
    }

    /// Triangulate one ExPolygon (contour + holes) with earcut and feed the
    /// resulting triangles through the `tess_vertex` callback as a
    /// `GL_TRIANGLES` primitive stream. This stands in for the GLU input
    /// feeding (Tesselate.cpp:35-54 / 76-96) plus the GLU-driven callbacks.
    fn tesselate_one_expoly(&mut self, expoly: &ExPolygon) {
        // Build the flat coordinate buffer in unscaled mm, contour first then
        // holes, exactly as the GLU vertex feeding does (Tesselate.cpp:37-53):
        //   coords.emplace_back(unscale<double>(pt[0]));
        //   coords.emplace_back(unscale<double>(pt[1]));
        let mut vertices: Vec<f64> = Vec::new();
        let mut hole_indices: Vec<usize> = Vec::new();

        push_polygon_coords(&mut vertices, &expoly.contour); // contour (Tesselate.cpp:37-42)
        for poly in &expoly.holes {
            // gluTessBeginContour per hole (Tesselate.cpp:45). Earcut marks each
            // hole by the vertex index at which it starts.
            hole_indices.push(vertices.len() / 2);
            push_polygon_coords(&mut vertices, poly); // hole vertices (Tesselate.cpp:46-51)
        }

        if vertices.len() < 6 {
            // Fewer than 3 contour vertices: GLU emits no triangles.
            return;
        }

        // earcut triangulation (2D). Returns a flat list of vertex indices,
        // 3 per triangle. This replaces the native GLU tessellator core.
        let indices = match earcutr::earcut(&vertices, &hole_indices, 2) {
            Ok(idx) => idx,
            // tessError is a no-op in C++ (Tesselate.cpp:165-170); on failure we
            // simply emit no triangles for this region.
            Err(_) => {
                self.tess_error();
                return;
            }
        };

        // Feed the triangles through the GLU callback state machine as a
        // GL_TRIANGLES primitive (Tesselate.cpp:110-156).
        self.tess_begin(GlPrimitive::Triangles); // tessBegin (Tesselate.cpp:110-115)
        for tri in indices.chunks_exact(3) {
            for &vi in tri {
                let data = [vertices[vi * 2], vertices[vi * 2 + 1], 0.0];
                self.tess_vertex(Some(&data)); // tessVertex (Tesselate.cpp:122-157)
            }
        }
        self.tess_end(); // tessEnd (Tesselate.cpp:117-120)
    }

    /// Tesselate.cpp:110-115
    fn tess_begin(&mut self, which: GlPrimitive) {
        debug_assert!(matches!(
            which,
            GlPrimitive::Triangles | GlPrimitive::TriangleFan | GlPrimitive::TriangleStrip
        )); // assert(which == GL_TRIANGLES || ...); (Tesselate.cpp:112)
        self.m_primitive_type = which; // Tesselate.cpp:113
        self.m_num_points = 0; // Tesselate.cpp:114
    }

    /// Tesselate.cpp:117-120
    fn tess_end(&mut self) {
        self.m_num_points = 0; // Tesselate.cpp:119
    }

    /// Tesselate.cpp:122-157
    fn tess_vertex(&mut self, data: Option<&[f64; 3]>) {
        let ptr = match data {
            None => return, // if (data == nullptr) return; (Tesselate.cpp:124-125)
            Some(p) => p,   // const GLdouble *ptr = (const GLdouble*)data; (Tesselate.cpp:126)
        };
        self.m_num_points += 1; // ++ m_num_points; (Tesselate.cpp:127)
        if self.m_num_points == 1 {
            self.m_pt0.copy_from_slice(ptr); // memcpy(m_pt0, ptr, sizeof(GLdouble) * 3); (Tesselate.cpp:129)
        } else if self.m_num_points == 2 {
            self.m_pt1.copy_from_slice(ptr); // memcpy(m_pt1, ptr, sizeof(GLdouble) * 3); (Tesselate.cpp:131)
        } else {
            let mut flip = self.m_flipped; // bool flip = m_flipped; (Tesselate.cpp:133)
            if self.m_primitive_type == GlPrimitive::TriangleStrip && self.m_num_points == 4 {
                // Tesselate.cpp:134
                flip = !flip; // Tesselate.cpp:135
                self.m_num_points = 2; // Tesselate.cpp:136
            }
            // m_output_triangles.emplace_back(m_pt0[0], m_pt0[1], m_z); (Tesselate.cpp:138)
            self.m_output_triangles
                .push(Vec3d::new(self.m_pt0[0], self.m_pt0[1], self.m_z));
            if flip {
                // Tesselate.cpp:139-141
                self.m_output_triangles
                    .push(Vec3d::new(ptr[0], ptr[1], self.m_z));
                self.m_output_triangles
                    .push(Vec3d::new(self.m_pt1[0], self.m_pt1[1], self.m_z));
            } else {
                // Tesselate.cpp:142-145
                self.m_output_triangles
                    .push(Vec3d::new(self.m_pt1[0], self.m_pt1[1], self.m_z));
                self.m_output_triangles
                    .push(Vec3d::new(ptr[0], ptr[1], self.m_z));
            }
            if self.m_primitive_type == GlPrimitive::TriangleStrip {
                // Tesselate.cpp:146
                self.m_pt0 = self.m_pt1; // memcpy(m_pt0, m_pt1, sizeof(GLdouble) * 3); (Tesselate.cpp:147)
                self.m_pt1.copy_from_slice(ptr); // memcpy(m_pt1, ptr, sizeof(GLdouble) * 3); (Tesselate.cpp:148)
            } else if self.m_primitive_type == GlPrimitive::TriangleFan {
                // Tesselate.cpp:149
                self.m_pt1.copy_from_slice(ptr); // memcpy(m_pt1, ptr, sizeof(GLdouble) * 3); (Tesselate.cpp:150)
            } else {
                debug_assert!(self.m_primitive_type == GlPrimitive::Triangles); // assert (Tesselate.cpp:152)
                debug_assert!(self.m_num_points == 3); // assert (Tesselate.cpp:153)
                self.m_num_points = 0; // Tesselate.cpp:154
            }
        }
    }

    /// Tesselate.cpp:159-163 (tessCombine)
    ///
    /// Records an intersection vertex created by the tessellator at a
    /// self-intersection. The earcut backend does not split self-intersections,
    /// so this is retained for fidelity but is not exercised by that backend.
    #[allow(dead_code)]
    fn tess_combine(&mut self, new_vertex: &[f64; 3]) -> *const f64 {
        // m_intersection_points.emplace_back(newVertex[0], newVertex[1], m_z); (Tesselate.cpp:161)
        self.m_intersection_points
            .push_back(Vec3d::new(new_vertex[0], new_vertex[1], self.m_z));
        // *outData = m_intersection_points.back().data(); (Tesselate.cpp:162)
        let back = self.m_intersection_points.back().unwrap();
        &back.x as *const f64
    }

    /// Tesselate.cpp:165-170 (tessError) — no-op (error string printing is
    /// commented out in C++).
    fn tess_error(&self) {
        // const GLubyte *errorStr; (Tesselate.cpp:167)
        // errorStr = gluErrorString(errorCode); (Tesselate.cpp:168)
        // printf("Error: %s\n", (const char*)errorStr); (Tesselate.cpp:169)
    }
}

/// Append a polygon's vertices (unscaled mm) to a flat earcut coordinate
/// buffer. Mirrors the per-vertex feeding loop (Tesselate.cpp:37-42 / 46-51):
///   coords.emplace_back(unscale<double>(pt[0]));
///   coords.emplace_back(unscale<double>(pt[1]));
fn push_polygon_coords(vertices: &mut Vec<f64>, poly: &Polygon) {
    for pt in &poly.points {
        vertices.push(unscale(pt.x)); // unscale<double>(pt[0]) (Tesselate.cpp:38)
        vertices.push(unscale(pt.y)); // unscale<double>(pt[1]) (Tesselate.cpp:39)
    }
}

