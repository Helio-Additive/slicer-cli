#[cfg(test)]
mod tests {
    use super::*;
    use crate::geometry::{Point, Polygon};

    fn unit_square() -> ExPolygon {
        // 10mm x 10mm square (scaled coords).
        let s = crate::scale(10.0);
        ExPolygon::new(Polygon::new(vec![
            Point::new(0, 0),
            Point::new(s, 0),
            Point::new(s, s),
            Point::new(0, s),
        ]))
    }

    #[test]
    fn test_vec3d_creation() {
        let v = Vec3d::new(1.0, 2.0, 3.0);
        assert_eq!(v.x, 1.0);
        assert_eq!(v.y, 2.0);
        assert_eq!(v.z, 3.0);
    }

    #[test]
    fn test_normals_constants() {
        assert_eq!(NORMALS_UP, false);
        assert_eq!(NORMALS_DOWN, true);
    }

    #[test]
    fn test_triangulate_square_3d() {
        let poly = unit_square();
        let tris = triangulate_expolygon_3d(&poly, 5.0, NORMALS_UP).unwrap();
        // A quad triangulates into 2 triangles = 6 vertices.
        assert_eq!(tris.len(), 6);
        // All vertices at the requested Z.
        for v in &tris {
            assert!((v.z - 5.0).abs() < 1e-9);
        }
    }

    #[test]
    fn test_triangulate_square_2d_and_2f() {
        let poly = unit_square();
        let d = triangulate_expolygon_2d(&poly, NORMALS_UP).unwrap();
        let f = triangulate_expolygon_2f(&poly, NORMALS_UP).unwrap();
        assert_eq!(d.len(), 6);
        assert_eq!(f.len(), 6);
        for (vd, vf) in d.iter().zip(f.iter()) {
            assert!((vd.x - vf.x as f64).abs() < 1e-6);
            assert!((vd.y - vf.y as f64).abs() < 1e-6);
        }
    }

    #[test]
    fn test_flip_reverses_winding() {
        let poly = unit_square();
        let up = triangulate_expolygon_2d(&poly, NORMALS_UP).unwrap();
        let down = triangulate_expolygon_2d(&poly, NORMALS_DOWN).unwrap();
        assert_eq!(up.len(), down.len());
        // For each triangle, NORMALS_DOWN swaps vertices 1 and 2 (Tesselate.cpp:139-145).
        for tri in 0..(up.len() / 3) {
            let i = tri * 3;
            assert_eq!(up[i], down[i]); // pt0 unchanged
            assert_eq!(up[i + 1], down[i + 2]);
            assert_eq!(up[i + 2], down[i + 1]);
        }
    }

    #[test]
    fn test_empty_expolygons() {
        let polys: ExPolygons = ExPolygons::new();
        let tris = triangulate_expolygons_3d(&polys, 0.0, NORMALS_UP).unwrap();
        assert_eq!(tris.len(), 0);
    }

    #[test]
    fn test_degenerate_returns_empty() {
        // Fewer than 3 vertices -> no triangles.
        let poly = ExPolygon::new(Polygon::new(vec![Point::new(0, 0), Point::new(100, 0)]));
        let tris = triangulate_expolygon_3d(&poly, 0.0, NORMALS_UP).unwrap();
        assert_eq!(tris.len(), 0);
    }
}
