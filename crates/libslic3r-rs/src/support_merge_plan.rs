/// SupportMergePlan.hpp:33-106
#[derive(Debug, Clone, PartialEq)]
pub struct SupportMergePlan {
    // Object layer print_z, ascending. Parallel to layer_heights / candidates_per_layer.
    pub layer_print_z: Vec<f64>,
    pub layer_heights: Vec<f64>,
    // Filaments the object prints on a given object layer. Empty for layers the object does not print at all.
    pub candidates_per_layer: Vec<Vec<Candidate>>,
    // Candidates for support contact/interface. This differs when support_interface_filament is explicit.
    pub interface_candidates_per_layer: Vec<Vec<Candidate>>,
    // Fixed layer ladders, generated by the same planner as the model. Empty means a one-layer candidate.
    pub fixed_bands_per_filament: BTreeMap<i32, Vec<AdaptiveLayerBand>>,

    pub enabled: bool,

    // The fixed grid partition, ascending and non overlapping. Layers above the last closed band are covered
    // by no slab at all: those stay on the fine grid.
    pub slabs: Vec<Slab>,
    // Index into slabs per object layer, -1 for a layer no slab covers.
    pub slab_index_per_layer: Vec<i32>,
    // False when an explicitly pinned interface filament cannot print the slabs this object folds onto. The
    // contact/interface chains then stay on the fine grid while the sparse base still folds.
    pub interface_fold_enabled: bool,
}

