//! Port of `libslic3r/SupportMergePlan.hpp` and `SupportMergePlan.cpp`.
//!
//! BBS multi-diameter: which filaments the object prints at a given height, so the support layers can be
//! merged into slabs a large nozzle is actually able to extrude.
//!
//! Two consumers query this plan, and they need different things:
//!   - normal support merges finished areas layer by layer and asks per slab: candidates_for_slab() and
//!     friends.
//!   - tree support folds its node chains onto the grid before any area exists, and asks for the whole
//!     partition at once: slabs / slab_for_layer().
//!
//! `SupportMergePlan::Candidate` and `SupportMergePlan::Slab` are [`Candidate`] and [`Slab`] of this module.
//!
//! C++ reference: `references/BambuStudio/src/libslic3r/SupportMergePlan.{hpp,cpp}`.

