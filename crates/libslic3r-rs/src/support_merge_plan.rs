/// `std::lower_bound(v.begin(), v.end(), value)`: the index of the first element not less than `value`.
fn lower_bound(v: &[f64], value: f64) -> usize {
    v.partition_point(|e| *e < value)
}

/// `std::upper_bound(v.begin(), v.end(), value)`: the index of the first element `value` is less than.
fn upper_bound(v: &[f64], value: f64) -> usize {
    v.partition_point(|e| !(value < *e))
}

/// SupportMergePlan.cpp:15-41 — the file-static `candidates_in_span(plan, candidates_per_layer, ...)`.
fn candidates_in_span(
    plan: &SupportMergePlan,
    candidates_per_layer: &[Vec<Candidate>],
    bottom_z: f64,
    top_z: f64,
) -> Vec<Candidate> {
    let mut out: Vec<Candidate> = Vec::new();
    if !plan.enabled {
        return out;
    }

    // An object layer overlaps the span when it sticks out above bottom_z and starts below top_z.
    let first = lower_bound(&plan.layer_print_z, bottom_z + EPSILON);
    for idx in first..plan.layer_print_z.len() {
        if plan.layer_print_z[idx] - plan.layer_heights[idx] > top_z - EPSILON {
            break;
        }
        for candidate in &candidates_per_layer[idx] {
            let same = out.iter().position(|other| other.filament_id == candidate.filament_id);
            if same.is_none() {
                out.push(*candidate);
            }
        }
    }
    out
}

impl SupportMergePlan {
    /// SupportMergePlan.cpp:43-46
    ///
    /// Filaments the object prints on any layer overlapping (bottom_z, top_z].
    pub fn candidates_in_span(&self, bottom_z: f64, top_z: f64) -> Vec<Candidate> {
        candidates_in_span(self, &self.candidates_per_layer, bottom_z, top_z)
    }

    /// SupportMergePlan.cpp:48-58
    ///
    /// Filaments that may extrude a slab of height ending at top_z. Only the ones the object prints over the
    /// slab's own Z span qualify.
    pub fn candidates_for_slab(&self, top_z: f64, height: f64) -> Vec<Candidate> {
        let mut candidates = self.candidates_in_span(top_z - height, top_z);
        if candidates.is_empty() {
            // A support layer sits in the gap between two object layers, so a thin span may not overlap any of
            // them at all. Widen it by one object layer rather than give up.
            let slack = self.base_height_at(top_z) + EPSILON;
            candidates = self.candidates_in_span(top_z - height - slack, top_z + slack);
        }
        candidates
    }

    /// SupportMergePlan.cpp:60-68
    ///
    /// Coarsest filament whose fixed band exactly matches that slab, or an invalid candidate when none does.
    pub fn coarsest_for_slab(&self, top_z: f64, height: f64) -> Candidate {
        let mut best = Candidate::default();
        for candidate in &self.candidates_for_slab(top_z, height) {
            if (self.fixed_band_height_at(candidate, top_z) - height).abs() < EPSILON {
                if !best.valid() || candidate.nozzle_diameter > best.nozzle_diameter {
                    best = *candidate;
                }
            }
        }
        best
    }

    /// SupportMergePlan.cpp:70-85
    ///
    /// Finest interface filament whose fixed band exactly matches the slab, or an invalid candidate.
    pub fn finest_interface_for_slab(&self, top_z: f64, height: f64) -> Candidate {
        let mut best = Candidate::default();
        let mut candidates = candidates_in_span(self, &self.interface_candidates_per_layer, top_z - height, top_z);
        if candidates.is_empty() {
            let slack = self.base_height_at(top_z) + EPSILON;
            candidates =
                candidates_in_span(self, &self.interface_candidates_per_layer, top_z - height - slack, top_z + slack);
        }
        for candidate in &candidates {
            if (self.fixed_band_height_at(candidate, top_z) - height).abs() < EPSILON
                && (!best.valid() || candidate.nozzle_diameter < best.nozzle_diameter)
            {
                best = *candidate;
            }
        }
        best
    }

    /// SupportMergePlan.cpp:87-100
    ///
    /// Tallest fixed interface band ending at top_z among the filaments of this span. 0 when there is none.
    pub fn max_interface_height(&self, top_z: f64, height: f64) -> f64 {
        let mut candidates = candidates_in_span(self, &self.interface_candidates_per_layer, top_z - height, top_z);
        if candidates.is_empty() {
            let slack = self.base_height_at(top_z) + EPSILON;
            candidates =
                candidates_in_span(self, &self.interface_candidates_per_layer, top_z - height - slack, top_z + slack);
        }
        let mut max_height: f64 = 0.0;
        for candidate in &candidates {
            max_height = std_max(max_height, self.fixed_band_height_at(candidate, top_z));
        }
        max_height
    }

    /// SupportMergePlan.cpp:102-108
    ///
    /// Tallest fixed base band ending at top_z among the filaments of this span. 0 when there is none.
    pub fn max_height_for_slab(&self, top_z: f64, height: f64) -> f64 {
        let mut max_height: f64 = 0.0;
        for candidate in &self.candidates_for_slab(top_z, height) {
            max_height = std_max(max_height, self.fixed_band_height_at(candidate, top_z));
        }
        max_height
    }

    /// SupportMergePlan.cpp:110-120
    ///
    /// Object layer height at top_z, the granularity every merged slab is a multiple of.
    pub fn base_height_at(&self, top_z: f64) -> f64 {
        if !self.enabled || self.layer_print_z.is_empty() {
            return 0.0;
        }

        // The object layer ending at or just below top_z sets the granularity there.
        let it = upper_bound(&self.layer_print_z, top_z + EPSILON);
        if it == 0 {
            return self.layer_heights[0];
        }
        self.layer_heights[it - 1]
    }

    /// SupportMergePlan.cpp:122-141
    ///
    /// Height of candidate's fixed band ending at top_z. 0 means top_z is not on that nozzle's ladder.
    pub fn fixed_band_height_at(&self, candidate: &Candidate, top_z: f64) -> f64 {
        if !self.enabled || self.layer_print_z.is_empty() {
            return 0.0;
        }

        let layer_it = lower_bound(&self.layer_print_z, top_z - EPSILON);
        if layer_it == self.layer_print_z.len() || self.layer_print_z[layer_it] > top_z + EPSILON {
            return 0.0;
        }
        let layer_idx = layer_it;
        if candidate.band_size < 2 {
            return self.layer_heights[layer_idx];
        }

        let Some(bands) = self.fixed_bands_per_filament.get(&candidate.filament_id) else {
            return 0.0;
        };
        let band_it = bands.partition_point(|band| band.top_idx < layer_idx);
        if band_it != bands.len() && bands[band_it].top_idx == layer_idx {
            bands[band_it].merged_height
        } else {
            0.0
        }
    }

    /// SupportMergePlan.cpp:143-177
    ///
    /// Coarsest candidate whose fixed band contains print_z. band_height receives that band's full height.
    pub fn coarsest_band_containing(&self, print_z: f64, band_height: &mut f64) -> Candidate {
        *band_height = 0.0;
        let mut best = Candidate::default();
        if !self.enabled || self.layer_print_z.is_empty() {
            return best;
        }

        // Independent support layers may end between object layers. Use the object layer whose Z span contains
        // print_z; requiring an exact top-Z match would give every such support layer the full slab line width.
        let layer_it = lower_bound(&self.layer_print_z, print_z - EPSILON);
        if layer_it == self.layer_print_z.len() {
            return best;
        }
        let layer_idx = layer_it;

        for candidate in &self.candidates_per_layer[layer_idx] {
            let mut candidate_height = self.layer_heights[layer_idx];
            if candidate.band_size > 1 {
                let Some(bands) = self.fixed_bands_per_filament.get(&candidate.filament_id) else {
                    continue;
                };
                let band_it = bands.partition_point(|band| band.top_idx < layer_idx);
                if band_it == bands.len() || bands[band_it].bottom_idx > layer_idx {
                    continue;
                }
                candidate_height = bands[band_it].merged_height;
            }
            if !best.valid() || candidate.nozzle_diameter > best.nozzle_diameter {
                best = *candidate;
                *band_height = candidate_height;
            }
        }
        best
    }

    /// SupportMergePlan.cpp:179-185
    ///
    /// The slab covering that object layer, or `None` (nullptr) when the layer stays on the fine grid.
    pub fn slab_for_layer(&self, layer_idx: usize) -> Option<&Slab> {
        if layer_idx >= self.slab_index_per_layer.len() {
            return None;
        }
        let slab_idx = self.slab_index_per_layer[layer_idx];
        if slab_idx < 0 {
            None
        } else {
            Some(&self.slabs[slab_idx as usize])
        }
    }
}

/// `std::max(a, b)` for doubles: `(a < b) ? b : a`.
fn std_max(a: f64, b: f64) -> f64 {
    if a < b {
        b
    } else {
        a
    }
}

/// SupportMergePlan.cpp:187-254
///
/// Cut the object layers into the slab partition the support folds onto. Every nozzle anchors its bands at
/// the object base, so walking up from the bed and always taking the band that starts exactly here and
/// reaches highest follows the coarsest ladder without ever stepping off it.
fn expand_slabs(plan: &mut SupportMergePlan, extruded_per_layer: Option<&[Vec<i32>]>) {
    let num_layers = plan.layer_print_z.len();
    plan.slab_index_per_layer.clear();
    plan.slab_index_per_layer.resize(num_layers, -1);
    if plan.fixed_bands_per_filament.is_empty() {
        return;
    }

    let mut next_bottom: usize = 0;
    while next_bottom < num_layers {
        let mut best: Option<Candidate> = None;
        let mut best_band: Option<AdaptiveLayerBand> = None;
        for (entry_first, bands) in &plan.fixed_bands_per_filament {
            let band_it = bands.partition_point(|band| band.bottom_idx < next_bottom);
            if band_it == bands.len() || bands[band_it].bottom_idx != next_bottom || bands[band_it].top_idx >= num_layers {
                continue;
            }
            let band = &bands[band_it];
            // The nozzle has to be one the object actually prints with where the band ends, or the support
            // would borrow a tool from a height nothing else uses there.
            let at_top = &plan.candidates_per_layer[band.top_idx];
            let Some(cand) = at_top.iter().find(|candidate| candidate.filament_id == *entry_first) else {
                continue;
            };
            // A region keeping slices on a layer does not mean its filament is extruded there: its band may be
            // emitted at another layer. Pinning the slab to such a filament adds a tool change nothing else at
            // this height needs, and among equal nozzles the lowest filament id always wins.
            // A support filament the user picked is not extruded by the object, so it is exempt (nullptr).
            if let Some(extruded_per_layer) = extruded_per_layer {
                let extruded = &extruded_per_layer[band.top_idx];
                if !extruded.contains(entry_first) {
                    continue;
                }
            }
            // Reaching higher wins, and on a tie the coarser nozzle does: two filaments can share a ladder
            // while only one of them saves a tool change here.
            let better = match (&best_band, &best) {
                (Some(best_band), Some(best)) => {
                    band.top_idx > best_band.top_idx
                        || (band.top_idx == best_band.top_idx && cand.nozzle_diameter > best.nozzle_diameter)
                }
                _ => true,
            };
            if better {
                best = Some(*cand);
                best_band = Some(*band);
            }
        }
        let (Some(best), Some(best_band)) = (best, best_band) else {
            // Nothing starts here, so this layer stays on the fine grid and the cursor moves up by one.
            next_bottom += 1;
            continue;
        };

        let mut slab = Slab::default();
        slab.bottom_idx = next_bottom;
        slab.top_idx = best_band.top_idx;
        slab.top_z = plan.layer_print_z[slab.top_idx];
        slab.height = best_band.merged_height;
        slab.filament_id = best.filament_id;
        slab.nozzle_diameter = best.nozzle_diameter;
        slab.bottom_anchor = slab.bottom_idx == 0;

        let slab_id = plan.slabs.len() as i32;
        for idx in slab.bottom_idx..=slab.top_idx {
            plan.slab_index_per_layer[idx] = slab_id;
        }
        plan.slabs.push(slab);
        next_bottom = slab.top_idx + 1;
    }
}

