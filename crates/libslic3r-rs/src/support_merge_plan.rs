/// SupportMergePlan.cpp:256-403
pub fn make_support_merge_plan(object: &SupportMergePlanObject<'_>) -> SupportMergePlan {
    let mut plan = SupportMergePlan::default();

    if !object.uses_multiple_nozzle_diameters {
        return plan;
    }

    let layers = &object.layers;
    if layers.len() < 2 {
        return plan;
    }

    plan.layer_print_z.reserve(layers.len());
    plan.layer_heights.reserve(layers.len());
    for layer in layers {
        plan.layer_print_z.push(layer.print_z);
        plan.layer_heights.push(layer.height);
    }

    let grid_nozzle: f64 = object.grid_nozzle;
    let base_height: f64 = object.base_height;

    let make_candidate = |filament_id: i32| -> Candidate {
        let mut candidate = Candidate::default();
        candidate.filament_id = filament_id;
        candidate.nozzle_diameter = f64::from((object.nozzle_diameter_for_filament)(filament_id as u32));
        candidate.window = adaptive_layer_height_range(candidate.nozzle_diameter);
        candidate.band_size = adaptive_layer_band_size(candidate.nozzle_diameter, grid_nozzle, base_height);
        candidate
    };

    // The C++ lambda captures `plan` by reference; here the two members it touches are passed in.
    let ensure_fixed_grid = |fixed_bands_per_filament: &mut BTreeMap<i32, Vec<AdaptiveLayerBand>>,
                             layer_heights: &[f64],
                             candidate: &Candidate| {
        if candidate.band_size > 1 && !fixed_bands_per_filament.contains_key(&candidate.filament_id) {
            fixed_bands_per_filament.insert(
                candidate.filament_id,
                build_adaptive_layer_bands(layer_heights, candidate.band_size, &candidate.window, &[]),
            );
        }
    };

    let add_candidate = |fixed_bands_per_filament: &mut BTreeMap<i32, Vec<AdaptiveLayerBand>>,
                         layer_heights: &[f64],
                         candidates: &mut Vec<Candidate>,
                         filament_id: i32,
                         allow_soluble: bool| {
        if filament_id <= 0 || (!allow_soluble && (object.filament_soluble)((filament_id - 1) as usize)) {
            return;
        }
        let same = candidates.iter().position(|other| other.filament_id == filament_id);
        if same.is_some() {
            return;
        }
        let candidate = make_candidate(filament_id);
        if candidate.nozzle_diameter > EPSILON {
            candidates.push(candidate);
            ensure_fixed_grid(fixed_bands_per_filament, layer_heights, &candidate);
        }
    };

    plan.candidates_per_layer.resize(layers.len(), Vec::new());
    plan.interface_candidates_per_layer.resize(layers.len(), Vec::new());

    // A filament value of 0 means "whatever the object prints with". Resolve those choices per object layer,
    // because a fine nozzle available elsewhere in the object must not keep a thin support contact at this Z.
    let mut object_filaments: Vec<Candidate> = Vec::new();
    for extruders in &object.model_part_extruders {
        for &filament_id in extruders {
            add_candidate(
                &mut plan.fixed_bands_per_filament,
                &plan.layer_heights,
                &mut object_filaments,
                filament_id,
                false,
            );
        }
    }

    let mut object_candidates: Vec<Vec<Candidate>> = vec![Vec::new(); layers.len()];
    // Filaments the object actually extrudes per layer, collected like ToolOrdering::collect_extruders():
    // walls only where perimeters exist, one slot per fill island. Listing both infill filaments whenever
    // any fill exists pins the slab to a filament this height never extrudes.
    // ToolOrdering's extruder_override (per-layer tool changes of a single-filament plate) is not applied,
    // like the candidates above; height range modifiers are already part of the region config.
    let mut extruded_per_layer: Vec<Vec<i32>> = vec![Vec::new(); layers.len()];
    for layer_idx in 0..layers.len() {
        let candidates = &mut object_candidates[layer_idx];
        for layerm in &layers[layer_idx].regions {
            if layerm.slices_empty {
                continue;
            }
            let extruded = &mut extruded_per_layer[layer_idx];
            if !layerm.perimeters_empty {
                extruded.push(layerm.wall_filament);
            }
            for &slot in &layerm.fill_filament_slots {
                extruded.push(slot);
            }
            add_candidate(
                &mut plan.fixed_bands_per_filament,
                &plan.layer_heights,
                candidates,
                layerm.wall_filament,
                false,
            );
            add_candidate(
                &mut plan.fixed_bands_per_filament,
                &plan.layer_heights,
                candidates,
                layerm.sparse_infill_filament,
                false,
            );
            add_candidate(
                &mut plan.fixed_bands_per_filament,
                &plan.layer_heights,
                candidates,
                layerm.solid_infill_filament,
                false,
            );
        }
        if candidates.is_empty() && !layers[layer_idx].empty {
            *candidates = object_filaments.clone();
        }
    }

    let support_filament: i32 = object.support_filament;
    if support_filament > 0 {
        if !(object.filament_soluble)((support_filament - 1) as usize) {
            let candidate = make_candidate(support_filament);
            if candidate.nozzle_diameter > EPSILON {
                ensure_fixed_grid(&mut plan.fixed_bands_per_filament, &plan.layer_heights, &candidate);
                for candidates in &mut plan.candidates_per_layer {
                    candidates.push(candidate);
                }
            }
        }
    } else {
        plan.candidates_per_layer = object_candidates.clone();
    }

    let interface_filament: i32 = object.support_interface_filament;
    if interface_filament > 0 {
        let candidate = make_candidate(interface_filament);
        if candidate.nozzle_diameter > EPSILON {
            ensure_fixed_grid(&mut plan.fixed_bands_per_filament, &plan.layer_heights, &candidate);
            for candidates in &mut plan.interface_candidates_per_layer {
                candidates.push(candidate);
            }
        }
    } else {
        plan.interface_candidates_per_layer = object_candidates;
    }

    expand_slabs(&mut plan, if support_filament > 0 { None } else { Some(&extruded_per_layer) });

    // The roof is printed with the pinned interface filament, so it may only be folded onto a slab that
    // filament can actually extrude. Nothing can make a 0.4 nozzle lay down a band only a 0.8 one reaches,
    // so an object whose slabs do not all match the pinned nozzle keeps its contact chains on the fine grid.
    if interface_filament > 0 {
        let interface_nozzle: f64 = f64::from((object.nozzle_diameter_for_filament)(interface_filament as u32));
        plan.interface_fold_enabled = !plan.slabs.is_empty() && interface_nozzle > EPSILON;
        for slab in &plan.slabs {
            if (slab.nozzle_diameter - interface_nozzle).abs() > EPSILON {
                plan.interface_fold_enabled = false;
                break;
            }
        }
    }

    plan.enabled = true;
    plan
}
