// Generator of the vectors of tests/config_native_parity.rs: libslic3r's Config.hpp / Config.cpp
// at the pin (references/BambuStudio/src/libslic3r), driven class by class.
//
// Build, with REPO = this repository, BUILD = a built tree of the Bambu Studio engine
// (docs/building.md, -DENGINE=bambu) and DATA = this directory: compile with the compile line the
// build uses for a libslic3r source (its defines and include directories, the override layer
// $REPO/libslic3r/bambustudio before the pin, -std=c++17 -O3 -DNDEBUG and the forced include of
// cgal_54_compat.hpp), then link with the build's libslic3r_core and the libraries it links:
//
//   c++ <the build's defines and include directories> -std=c++17 -O3 -DNDEBUG \
//       -include $REPO/libslic3r/bambustudio/cgal_54_compat.hpp -c $DATA/gen.cpp -o gen.o
//   c++ gen.o $BUILD/libslic3r_core.a <the libraries libslic3r_core links> -o gen
//   ./gen <output directory>
//   cd <output directory> && for f in *.txt; do gzip -9 -n -c $f > $DATA/$f.gz; done
//
// It writes options_scalar.txt, options_vector.txt, option_pairs.txt, vector_ops.txt and
// config.txt (about 10 MB; the test reads them gzipped). The vectors in this directory were made
// on macOS arm64 with Apple clang (its default -ffp-contract=on), libc++, Apple's libc and
// Boost 1.90: the texts and values of malformed numbers (`iss >> double`, `sscanf("%lf")`, NaN
// payloads), what `ss << double` prints for a NaN and the values of `hash()` are those of that
// standard library. The run is deterministic.
//
// What the C++ leaves undefined is not given to it: an item that is empty after the trim in the
// classes whose items are numbers (the value pushed is uninitialized), ConfigOptionEnum<T> holding
// a value past its names, the substitution of an enum without a default (set(nullptr)), "key#n" in
// apply_only() of a key that is not a vector option here, the other nullability in
// ConfigOptionEnumsGenericTempl::set(), a commented INI text that starts with neither white space,
// ';' nor "generated by" (the loop never ends), vector operations that index past the end.
//
// Line format: tokens separated by one space. A text token is the hexadecimal of its bytes ("-"
// for the empty text), a double its 16 hexadecimal digits, an integer is decimal. Every line is
//   <op> <inputs...> => <outputs...>
// An option is written as <class> <n> <n value tokens> (see spec()); the state of an option
// after an operation as that plus type, nullable, is_nil, serialize, hash and, for a vector,
// size and vserialize (see dump()). A thrown exception is "!<K>" and the text of what(), K being
// U UnknownOptionException, N NoDefinitionException, T BadOptionTypeException,
// V BadOptionValueException, C ConfigurationError, R Slic3r::RuntimeError, X any other; the path
// of a scratch file in that text is "<FILE>". A configuration is "D" (the test definition below)
// or "N" (no definition), the number of options and for each its key and the option.

